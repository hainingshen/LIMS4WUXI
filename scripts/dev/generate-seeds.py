#!/usr/bin/env python3
"""Generate seed SQL and frontend constants from machine-readable specs."""

from __future__ import annotations

import csv
import json
from collections import defaultdict
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SPECS = ROOT / "docs" / "development" / "specs"
SQL_OUTPUT = ROOT / "backend" / "src" / "main" / "resources" / "db" / "migration" / (
    "V002__seed_roles_permissions_dictionaries.sql"
)
TS_OUTPUT = ROOT / "web-shared" / "src" / "generated" / "dictionaries.ts"


def read_csv(name: str) -> list[dict[str, str]]:
    path = SPECS / name
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return [{key: value.strip() for key, value in row.items()} for row in csv.DictReader(handle)]


def sql(value: str | int | bool | None) -> str:
    if value is None or value == "":
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return "'" + value.replace("'", "''") + "'"


def rows_sql(rows: list[list[str | int | bool | None]]) -> str:
    return ",\n".join("  (" + ", ".join(sql(value) for value in row) + ")" for row in rows)


def to_pascal_case(value: str) -> str:
    return "".join(part.capitalize() for part in value.lower().split("_"))


def ts_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def unique_in_order(values: list[str]) -> list[str]:
    seen: set[str] = set()
    result: list[str] = []
    for value in values:
        if value not in seen:
            seen.add(value)
            result.append(value)
    return result


def generate_sql(
    roles: list[dict[str, str]],
    permissions: list[dict[str, str]],
    dictionaries: list[dict[str, str]],
) -> str:
    role_rows = [
        [
            row["roleCode"],
            row["labelZh"],
            row["labelEn"],
            row["side"],
            row["description"],
            "ACTIVE",
        ]
        for row in roles
    ]
    permission_rows = [
        [row["actionCode"], row["roleCode"], row["access"], row["scope"], row["note"]]
        for row in permissions
    ]
    dictionary_rows = [
        [
            row["dictCode"],
            row["itemCode"],
            row["labelZh"],
            row["labelEn"],
            int(row["sortOrder"]),
            True,
        ]
        for row in dictionaries
    ]

    return "\n".join(
        [
            "-- Generated by scripts/dev/generate-seeds.py. Do not edit by hand.",
            "",
            "INSERT INTO role_definition (role_code, label_zh, label_en, side, description, status)",
            "VALUES",
            rows_sql(role_rows),
            "ON CONFLICT (role_code) DO UPDATE SET",
            "  label_zh = EXCLUDED.label_zh,",
            "  label_en = EXCLUDED.label_en,",
            "  side = EXCLUDED.side,",
            "  description = EXCLUDED.description,",
            "  status = EXCLUDED.status;",
            "",
            "INSERT INTO permission_matrix (action_code, role_code, access, scope, note)",
            "VALUES",
            rows_sql(permission_rows),
            "ON CONFLICT (action_code, role_code) DO UPDATE SET",
            "  access = EXCLUDED.access,",
            "  scope = EXCLUDED.scope,",
            "  note = EXCLUDED.note;",
            "",
            "INSERT INTO dictionary_item (dict_code, item_code, label_zh, label_en, sort_order, enabled)",
            "VALUES",
            rows_sql(dictionary_rows),
            "ON CONFLICT (dict_code, item_code) DO UPDATE SET",
            "  label_zh = EXCLUDED.label_zh,",
            "  label_en = EXCLUDED.label_en,",
            "  sort_order = EXCLUDED.sort_order,",
            "  enabled = EXCLUDED.enabled;",
            "",
        ]
    )


def ts_array(name: str, values: list[str]) -> list[str]:
    rendered = ", ".join(ts_string(value) for value in values)
    return [f"export const {name} = [{rendered}] as const;"]


def generate_ts(
    roles: list[dict[str, str]],
    permissions: list[dict[str, str]],
    dictionaries: list[dict[str, str]],
) -> str:
    dict_groups: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in dictionaries:
        dict_groups[row["dictCode"]].append(row)

    role_codes = [row["roleCode"] for row in roles]
    action_codes = unique_in_order([row["actionCode"] for row in permissions])
    dict_codes = list(dict_groups)

    lines: list[str] = [
        "/*",
        " * Generated by scripts/dev/generate-seeds.py. Do not edit by hand.",
        " */",
        "",
        "export type DictionaryItem = {",
        "  itemCode: string;",
        "  labelZh: string;",
        "  labelEn: string;",
        "  sortOrder: number;",
        "};",
        "",
        "export type RoleDefinition = {",
        "  roleCode: RoleCode;",
        "  labelZh: string;",
        "  labelEn: string;",
        "  side: \"INTERNAL\" | \"PORTAL\";",
        "  description: string;",
        "};",
        "",
        "export type PermissionMatrixRow = {",
        "  actionCode: PermissionActionCode;",
        "  roleCode: RoleCode;",
        "  access: string;",
        "  scope: string;",
        "  note: string;",
        "};",
        "",
        *ts_array("ROLE_CODES", role_codes),
        "export type RoleCode = (typeof ROLE_CODES)[number];",
        "",
        "export const ROLES = [",
    ]

    for row in roles:
        lines.append(
            "  { "
            f"roleCode: {ts_string(row['roleCode'])}, "
            f"labelZh: {ts_string(row['labelZh'])}, "
            f"labelEn: {ts_string(row['labelEn'])}, "
            f"side: {ts_string(row['side'])}, "
            f"description: {ts_string(row['description'])} "
            "},"
        )
    lines += [
        "] as const satisfies readonly RoleDefinition[];",
        "",
        *ts_array("PERMISSION_ACTION_CODES", action_codes),
        "export type PermissionActionCode = (typeof PERMISSION_ACTION_CODES)[number];",
        "",
        "export const PERMISSION_MATRIX = [",
    ]

    for row in permissions:
        lines.append(
            "  { "
            f"actionCode: {ts_string(row['actionCode'])}, "
            f"roleCode: {ts_string(row['roleCode'])}, "
            f"access: {ts_string(row['access'])}, "
            f"scope: {ts_string(row['scope'])}, "
            f"note: {ts_string(row['note'])} "
            "},"
        )
    lines += [
        "] as const satisfies readonly PermissionMatrixRow[];",
        "",
        *ts_array("DICTIONARY_CODES", dict_codes),
        "export type DictionaryCode = (typeof DICTIONARY_CODES)[number];",
        "",
        "export const DICTIONARY_ITEMS = {",
    ]

    for dict_code in dict_codes:
        lines.append(f"  {dict_code}: [")
        for row in sorted(dict_groups[dict_code], key=lambda item: (int(item["sortOrder"]), item["itemCode"])):
            lines.append(
                "    { "
                f"itemCode: {ts_string(row['itemCode'])}, "
                f"labelZh: {ts_string(row['labelZh'])}, "
                f"labelEn: {ts_string(row['labelEn'])}, "
                f"sortOrder: {int(row['sortOrder'])} "
                "},"
            )
        lines.append("  ],")
    lines += [
        "} as const satisfies Record<DictionaryCode, readonly DictionaryItem[]>;",
        "",
    ]

    for dict_code in dict_codes:
        item_codes = [row["itemCode"] for row in sorted(dict_groups[dict_code], key=lambda item: int(item["sortOrder"]))]
        type_name = to_pascal_case(dict_code)
        lines += [
            *ts_array(dict_code, item_codes),
            f"export type {type_name} = (typeof {dict_code})[number];",
            "",
        ]

    return "\n".join(lines)


def main() -> int:
    roles = read_csv("roles.csv")
    permissions = read_csv("permission_matrix.csv")
    dictionaries = read_csv("dictionaries.csv")

    SQL_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    TS_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    SQL_OUTPUT.write_text(generate_sql(roles, permissions, dictionaries), encoding="utf-8")
    TS_OUTPUT.write_text(generate_ts(roles, permissions, dictionaries), encoding="utf-8")

    print(f"Generated {SQL_OUTPUT.relative_to(ROOT)}")
    print(f"Generated {TS_OUTPUT.relative_to(ROOT)}")
    print(f"- roles: {len(roles)}")
    print(f"- permission rows: {len(permissions)}")
    print(f"- dictionary rows: {len(dictionaries)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
