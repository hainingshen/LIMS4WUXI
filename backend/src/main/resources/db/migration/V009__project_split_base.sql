create table project (
  id uuid primary key,
  biz_no varchar(64) not null unique,
  submission_id uuid not null references submission(id),
  customer_org_id uuid not null references customer_org(id),
  project_type varchar(32) not null,
  qualification_type varchar(32) not null,
  service_type varchar(32) not null,
  urgent_extra_fee_percent decimal(5,2),
  urgent_tat_days int,
  requires_glp boolean not null,
  requires_animal_test boolean not null,
  requires_ethics_review boolean not null,
  requires_nonstandard_review boolean not null,
  business_owner_id uuid not null references app_user(id),
  technical_owner_id uuid not null references app_user(id),
  sd_user_id uuid not null references app_user(id),
  status varchar(32) not null,
  planned_finish_at timestamptz,
  actual_finish_at timestamptz,
  health_status varchar(16) not null,
  health_score int not null,
  payment_status varchar(32) not null,
  created_at timestamptz not null default now(),
  created_by uuid,
  updated_at timestamptz not null default now(),
  updated_by uuid,
  deleted_at timestamptz,
  version int not null default 0,
  tenant_org_id uuid,
  legacy_id varchar(128),
  source_type varchar(32),
  migration_batch varchar(64),
  data_quality_score int,
  constraint ck_project_type check (project_type in ('STD_ACCREDITED', 'STD_NON_ACCREDITED', 'NON_STANDARD')),
  constraint ck_project_qualification_type check (qualification_type in ('CMA', 'CNAS', 'CMA_CNAS', 'NONE')),
  constraint ck_project_service_type check (service_type in ('NORMAL', 'URGENT')),
  constraint ck_project_status check (status in ('DRAFT', 'ACCEPTED', 'NONSTANDARD_REVIEW', 'QUOTABLE', 'QUOTED', 'CONTRACTED', 'WAITING_SAMPLE', 'SAMPLE_RECEIVED', 'PLAN_READY', 'IN_TESTING', 'REPORTING', 'PAYMENT_HOLD', 'RELEASED', 'ARCHIVED')),
  constraint ck_project_health_status check (health_status in ('NORMAL', 'WARNING', 'RISK')),
  constraint ck_project_health_score check (health_score between 0 and 100),
  constraint ck_project_payment_status check (payment_status in ('UNPAID', 'PARTIAL', 'PAID', 'GREEN_CHANNEL'))
);

create index ix_project_submission on project(submission_id);
create index ix_project_customer_org on project(customer_org_id);
create index ix_project_status on project(status);
